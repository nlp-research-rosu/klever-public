def sort_array(arr):
    return sorted(
        sorted(arr),
        key=lambda value: bin(value).count("1"),
    )


assert sort_array([1, 5, 2, 3, 4]) == [1, 2, 4, 3, 5]
assert sort_array([-2, -3, -4, -5, -6]) == [-4, -2, -6, -5, -3]
assert sort_array([1, 0, 2, 3, 4]) == [0, 1, 2, 4, 3]
assert sort_array([]) == []
assert sort_array([2, 5, 77, 4, 5, 3, 5, 7, 2, 3, 4]) == [2, 2, 4, 4, 3, 3, 5, 5, 5, 7, 77]
assert sort_array([3, 6, 44, 12, 32, 5]) == [32, 3, 5, 6, 12, 44]
assert sort_array([2, 4, 8, 16, 32]) == [2, 4, 8, 16, 32]
assert sort_array([3, 4]) == [4, 3]
assert sort_array([0, -1, 1, -2, 2, -3, 3, -4, 4]) == [0, -4, -2, -1, 1, 2, 4, -3, 3]
assert sort_array([7, 7, 3, 3, 1, 1, 0]) == [0, 1, 1, 3, 3, 7, 7]
assert sort_array([15, 8, 7, 16, -15, -8, -7, -16]) == [-16, -8, 8, 16, -7, 7, -15, 15]
assert sort_array([1023, 1024, 511, 512, 255, 256]) == [256, 512, 1024, 255, 511, 1023]
assert sort_array([-1023, -1024, -511, -512, -255, -256]) == [-1024, -512, -256, -255, -511, -1023]
assert sort_array([9, 10, 11, 12, 13, 14, 15, 16]) == [16, 9, 10, 12, 11, 13, 14, 15]
assert sort_array([-9, -10, -11, -12, -13, -14, -15, -16]) == [-16, -12, -10, -9, -14, -13, -11, -15]
assert sort_array([42, -42, 0, 1, -1, 2, -2]) == [0, -2, -1, 1, 2, -42, 42]
assert sort_array([31, 3, 5, 6, 9, 10, 12, 17, 18, 20, 24]) == [3, 5, 6, 9, 10, 12, 17, 18, 20, 24, 31]
assert sort_array([64, 32, 16, 8, 4, 2, 1, 0]) == [0, 1, 2, 4, 8, 16, 32, 64]
assert sort_array([-64, -32, -16, -8, -4, -2, -1, 0]) == [0, -64, -32, -16, -8, -4, -2, -1]
assert sort_array([1000000000000, -1000000000000, 999999999999, -999999999999]) == [-1000000000000, 1000000000000, -999999999999, 999999999999]
