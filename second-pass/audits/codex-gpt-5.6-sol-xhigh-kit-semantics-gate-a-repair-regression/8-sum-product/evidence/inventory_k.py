#!/usr/bin/env python3
"""Inventory every local K declaration/rule in the audited source tree."""

from __future__ import annotations

import collections
import re
from pathlib import Path


ROOT = Path("/tmp/audit-work/reconstruction")
files = (
    [ROOT / "reference-semantics" / "semantics.k"]
    + sorted((ROOT / "reference-semantics" / "semantics").glob("*.k"))
    + [ROOT / "verification.k", ROOT / "spec.k"]
)

start_re = re.compile(
    r"^\s*(configuration|syntax(?:\s+priority|\s+associativity)?|"
    r"rule|claim|context|alias)\b"
)
boundary_re = re.compile(
    r"^\s*(module|endmodule|imports|configuration|"
    r"syntax(?:\s+priority|\s+associativity)?|rule|claim|context|alias)\b"
)
flags = (
    "function",
    "total",
    "functional",
    "simplification",
    "priority",
    "concrete",
    "owise",
    "macro",
    "strict",
    "seqstrict",
    "symbol",
    "hook",
    "opaque",
)

records: list[dict[str, object]] = []
for path in files:
    lines = path.read_text(encoding="utf-8").splitlines()
    starts = [i for i, line in enumerate(lines) if start_re.match(line)]
    for pos, start in enumerate(starts):
        kind_match = start_re.match(lines[start])
        assert kind_match is not None
        kind = kind_match.group(1)
        end = len(lines)
        for i in range(start + 1, len(lines)):
            if boundary_re.match(lines[i]):
                end = i
                break
        text = " ".join(
            part.strip()
            for part in lines[start:end]
            if part.strip() and not part.lstrip().startswith("//")
        )
        # K attributes occur in square brackets. Restrict flag detection to
        # those blocks so source string literals such as Name("total") do not
        # masquerade as a [total] declaration.
        attribute_text = " ".join(re.findall(r"\[([^\]]*)\]", text))
        found_flags = [
            flag for flag in flags if re.search(rf"\b{flag}\b", attribute_text)
        ]
        if kind == "rule":
            classification = (
                "simplification-rule"
                if "simplification" in found_flags
                else "ordinary-rule"
            )
        else:
            classification = kind
        records.append(
            {
                "file": str(path.relative_to(ROOT)),
                "line": start + 1,
                "kind": kind,
                "classification": classification,
                "flags": found_flags,
                "text": text,
            }
        )

print("# Exhaustive source declaration/rule inventory")
print("# Generated by evidence/inventory_k.py from the clean scratch source copy.")
print("# One record appears for every configuration, syntax declaration, rule,")
print("# claim, context, or alias whose declaration begins in the selected sources.")
print()

by_file: dict[str, collections.Counter[str]] = collections.defaultdict(
    collections.Counter
)
overall: collections.Counter[str] = collections.Counter()
attribute_counts: collections.Counter[str] = collections.Counter()
for record in records:
    by_file[record["file"]][record["classification"]] += 1
    overall[record["classification"]] += 1
    attribute_counts.update(record["flags"])

print("SUMMARY")
print(f"files={len(files)} records={len(records)}")
print("overall=" + ", ".join(f"{key}:{overall[key]}" for key in sorted(overall)))
print(
    "attribute_flags="
    + ", ".join(f"{flag}:{attribute_counts[flag]}" for flag in flags)
)
for file in sorted(by_file):
    counts = ", ".join(
        f"{key}:{by_file[file][key]}" for key in sorted(by_file[file])
    )
    print(f"{file}: {counts}")
print()

for index, record in enumerate(records, 1):
    flag_text = ",".join(record["flags"]) if record["flags"] else "-"
    if str(record["file"]).startswith("reference-semantics/"):
        status = "TRUSTED_SUPPLIED_BASELINE"
    elif record["file"] == "verification.k":
        status = "PROOF_LOCAL_REVIEWED_IN_REVIEW_MD"
    else:
        status = "CLAIM_REVIEWED_IN_REVIEW_MD"
    print(
        f"{index:04d} {record['file']}:{record['line']} "
        f"{record['classification']} flags={flag_text} status={status}"
    )
    print(f"     {record['text']}")
